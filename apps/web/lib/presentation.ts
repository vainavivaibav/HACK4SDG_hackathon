// The backend has no meal-photo field. These are visibly labelled illustrations.
export function mealPhoto(m: Meal) {
  const text = (m.title + " " + m.description).toLowerCase();
  return (
    "/assets/" +
    (m.diet === "nonveg"
      ? "biryani-v2.jpg"
      : /pulao|rice bowl/.test(text)
        ? "pulao-v2.jpg"
        : "thali-v2.jpg")
  );
}
